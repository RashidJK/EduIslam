#!/usr/bin/env node
// Regenerates src/data/quran/surahs.generated.json from the configured provider.
// Surah names and verse counts are never hand-typed: they come from the provider and
// are checked against canonical totals (114 surahs, 6236 verses in the Hafs numbering)
// before the file is written. Run: npm run quran:metadata
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const API_BASE = process.env.VITE_QURAN_API_BASE ?? 'https://api.alquran.cloud/v1';
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../src/data/quran/surahs.generated.json');
const EXPECTED_SURAHS = 114;
const EXPECTED_VERSES = 6236;

const res = await fetch(`${API_BASE}/surah`);
if (!res.ok) throw new Error(`Provider responded ${res.status}`);
const body = await res.json();
const surahs = body?.data;
if (!Array.isArray(surahs)) throw new Error('Unexpected provider response shape');

const problems = [];
if (surahs.length !== EXPECTED_SURAHS) problems.push(`expected ${EXPECTED_SURAHS} surahs, got ${surahs.length}`);
const total = surahs.reduce((sum, s) => sum + s.numberOfAyahs, 0);
if (total !== EXPECTED_VERSES) problems.push(`expected ${EXPECTED_VERSES} verses, got ${total}`);
surahs.forEach((s, i) => {
  if (s.number !== i + 1) problems.push(`surah at index ${i} has number ${s.number}`);
  if (!Number.isInteger(s.numberOfAyahs) || s.numberOfAyahs < 3) problems.push(`surah ${s.number} has invalid verse count`);
  if (!s.name || !s.englishName) problems.push(`surah ${s.number} is missing a name`);
  if (!['Meccan', 'Medinan'].includes(s.revelationType)) problems.push(`surah ${s.number} has unknown revelation type`);
});
if (problems.length) {
  console.error('Refusing to write metadata:\n- ' + problems.join('\n- '));
  process.exit(1);
}

const output = {
  provenance: {
    provider: 'alquran-cloud',
    endpoint: `${API_BASE}/surah`,
    fetchedAt: new Date().toISOString(),
    note: 'Generated by scripts/fetch-quran-metadata.mjs. Do not edit by hand.',
  },
  surahs: surahs.map((s) => ({
    number: s.number,
    nameArabic: s.name,
    nameTransliterated: s.englishName,
    nameTranslated: s.englishNameTranslation,
    verseCount: s.numberOfAyahs,
    revelationType: s.revelationType,
  })),
};

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, JSON.stringify(output, null, 2) + '\n');
console.log(`Wrote ${surahs.length} surahs (${total} verses) to ${OUT}`);
